/**
 * Идентификация файла обмена информации о показаниях
 * одометра при выезде транспортного средства с парковки
 * (парковочного места)/при приеме транспортного средства
 * от другого водителя
 * (ИдИнфВыезд, таб-13.3)
 */

import { formatDate, formatTime } from '../../../../helpers'

export type TDepartureFileId = {
    /**
     * Идентификатор файла обмена информации о показаниях
     * одометра при выезде транспортного средства с парковки
     * (парковочного места)/при приеме транспортного средства
     * от другого водителя.
     * Содержит (повторяет) имя файла обмена.
     * (1-255 символов)
     */
    fileId: string

    /**
     * Дата и время формирования файла обмена информации
     * о показаниях одометра при выезде транспортного средства
     * с парковки (парковочного места)/при приеме транспортного
     * средства от другого водителя.
     */
    fileDateTime: Date

    /**
     * Электронная подпись файла обмена информации.
     * Представляется в кодировке Base64.
     */
    signature: string
}

export function formatDepartureFileId(data: TDepartureFileId) {
    return {
        "ИдФайлИнфВыезд": data.fileId,
        "ДатФайлИнфВыезд": formatDate(data.fileDateTime),
        "ВрФайлИнфВыезд": formatTime(data.fileDateTime),
        "ЭП": data.signature,
    }
}
