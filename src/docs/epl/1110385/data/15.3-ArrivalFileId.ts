/**
 * Идентификация файла обмена информации о показаниях
 * одометра при заезде транспортного средства на парковку
 * (парковочного места)/при сдаче транспортного средства
 * другому водителю
 * (ИдИнфЗаезд, таб-15.3)
 */

import { formatDate, formatTime } from '../../../../helpers'

export type TArrivalFileId = {
    /**
     * Идентификатор файла обмена информации о показаниях
     * одометра при заезде транспортного средства на парковку
     * (парковочного места)/при сдаче транспортного средства
     * другому водителю.
     * Содержит (повторяет) имя файла обмена.
     * (1-255 символов)
     */
    fileId: string

    /**
     * Дата и время формирования файла обмена информации
     * о показаниях одометра при заезде транспортного средства
     * с парковки (парковочного места)/при сдаче транспортного
     * средства другому водителю.
     */
    fileDateTime: Date

    /**
     * Электронная подпись файла обмена информации.
     * Представляется в кодировке Base64.
     */
    signature: string
}

export function formatArrivalFileId(data: TArrivalFileId) {
    return {
        "ИдФайлИнфЗаезд": data.fileId,
        "ДатФайлИнфЗаезд": formatDate(data.fileDateTime),
        "ВрФайлИнфЗаезд": formatTime(data.fileDateTime),
        "ЭП": data.signature,
    }
}
