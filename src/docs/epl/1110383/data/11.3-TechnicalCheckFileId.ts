/**
 * Идентификация файла обмена информации о результате
 * предрейсового или предсменного контроля технического
 * состояния транспортного средства и выпуске
 * транспортного средства на линию
 * (ИдИнфТехСост, таб-11.3)
 */

import { formatDate, formatTime } from '../../../../helpers'

export type TTechnicalCheckFileId = {
    /**
     * Идентификатор файла обмена информации о результате
     * предрейсового или предсменного контроля технического
     * состояния транспортного средства и выпуске
     * транспортного средства на линию.
     * Содержит (повторяет) имя файла обмена.
     * (1-255 символов)
     */
    fileId: string

    /**
     * Дата и время формирования файла обмена информации
     * о результате предрейсового или предсменного контроля
     * технического состояния транспортного средства
     * и выпуске транспортного средства на линию.
     */
    fileDateTime: Date

    /**
     * Электронная подпись файла обмена информации.
     * Представляется в кодировке Base64.
     */
    signature: string
}

export function formatTechnicalCheckFileId(data: TTechnicalCheckFileId) {
    return {
        "ИдФайлИнфТехСост": data.fileId,
        "ДатФайлИнфТехСост": formatDate(data.fileDateTime),
        "ВрФайлИнфТехСост": formatTime(data.fileDateTime),
        "ЭП": data.signature,
    }
}