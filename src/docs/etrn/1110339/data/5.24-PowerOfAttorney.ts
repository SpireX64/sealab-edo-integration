/**
 * Сведения о доверенности, используемой для подтверждения полномочий в электронной форме
 * (СвДовер, таб-5.24)
 */

import { formatDate } from '../../../../helpers'

export type TPowerOfAttorney = {
    /**
     * Дата совершения доверенности.
     */
    date: Date

    /**
     * Номер доверенности: порядковый.
     * (1-100 символов)
     */
    number?: string

    /**
     * Номер доверенности: идентификатор файла доверенности.
     * Содержит (повторяет) имя сформированного файла доверенности (без расширения).
     * (1-255 символов)
     */
    fileId: string

    /**
     * Идентифицирующие сведения об информационной системе,
     * которая предоставляет техническую возможность получения информации
     * о досрочном прекращении действия доверенности.
     * Унифицированный указатель (URL).
     * (1-500 символов)
     */
    revocationSystemUrl?: string
}

export function formatPowerOfAttorney(data: TPowerOfAttorney) {
    return {
        "ДатаДовер": formatDate(data.date),
        "НомерДовер": data.number,
        "ИдентДовер": data.fileId,
        "СведСистОтм": data.revocationSystemUrl,
    }
}
