/**
 * Сведения об опасном грузе
 * (СвОпГрузТип, таб-5.33)
 */

import { formatDate } from '../../../../helpers'

export type TDangerousGoodsInfo = {
    /**
     * Номер ООН в формате "UN XXXX", где:
     * "UN" – неизменяемое значение,
     * "XXXX" – идентификационный номер по списку опасных веществ по номерам ООН.
     * (4-50 символов)
     */
    unNumber: string

    /**
     * Надлежащее отгрузочное наименование опасного груза,
     * соответствующее номеру ООН.
     * (1-1000 символов)
     */
    shippingName: string

    /**
     * Техническое наименование.
     * (1-1000 символов)
     */
    technicalName?: string

    /**
     * Описание, уточняющее сферу охвата соответствующей позиции
     * в тех случаях, когда классификация, условия перевозки
     * и (или) химическая совместимость вещества могут варьироваться.
     * (1-1000 символов)
     */
    description?: string

    /**
     * Класс опасности грузов.
     * (1-3 символа)
     */
    hazardClass: string

    /**
     * Классификационный код опасных грузов.
     * Если значение классификационного кода в справочнике отсутствует,
     * должно быть указано значение "-".
     * (1-50 символов)
     */
    classificationCode?: string

    /**
     * Группа упаковки.
     * Если значение группы в справочнике отсутствует,
     * должно быть указано значение "-".
     * (1-50 символов)
     */
    packingGroup?: string

    /**
     * Знак опасности.
     * (1-50 символов)
     */
    hazardLabel: string

    /**
     * Код ограничения проезда через туннели.
     * Если значение в справочнике отсутствует,
     * должно быть указано значение "-".
     * (1-50 символов)
     */
    tunnelCode?: string

    /**
     * Название или символ каждого радионуклида,
     * или для смесей радионуклидов – общее описание или перечень
     * радионуклидов с наибольшими ограничениями.
     * (Доп. положения для класса 7)
     * (1-1000 символов)
     */
    radionuclide?: string

    /**
     * Описание физической и химической формы материала,
     * или указание что материал – радиоактивный материал особого вида
     * или с низкой способностью к рассеянию.
     * (Доп. положения для класса 7)
     * (1-1000 символов)
     */
    physicalChemicalForm?: string

    /**
     * Максимальная активность радиоактивного содержимого
     * во время перевозки, выраженная в беккерелях (Бк)
     * с обозначением приставки СИ, или масса делящегося материала
     * в граммах (г) или кратных единицах.
     * (Доп. положения для класса 7)
     * (1-1000 символов)
     */
    maxActivity?: string

    /**
     * Категория упаковки, транспортного пакета или контейнера (ДОПОГ):
     * I-БЕЛАЯ, II-ЖЕЛТАЯ, III-ЖЕЛТАЯ.
     * (Доп. положения для класса 7)
     * (1-50 символов)
     */
    packageCategory?: string

    /**
     * Транспортный индекс (TI) по ДОПОГ.
     * Не указывается для категории I-БЕЛАЯ.
     * (Доп. положения для класса 7)
     * (1-100 символов)
     */
    transportIndex?: string

    /**
     * Индекс безопасности по критичности (CSI)
     * для грузов, содержащих делящийся материал.
     * (Доп. положения для класса 7)
     * (1-100 символов)
     */
    criticalitySafetyIndex?: string

    /**
     * Опознавательный знак для каждого сертификата
     * об утверждении компетентного органа, применимый для данного груза
     * (радиоактивный материал особого вида, с низкой способностью
     * к рассеянию, делящийся материал, специальные условия,
     * конструкция упаковки или перевозка).
     * (Доп. положения для класса 7)
     * (1-1000 символов)
     */
    approvalCertificateId?: string

    /**
     * Полная активность груза в виде значения, кратного А2
     * (для материалов LSA-II и LSA-III, SCO-I, SCO-II, SCO-III).
     * Для радиоактивного материала с неограниченным А2 — значение "-".
     * (Доп. положения для класса 7)
     * (1-50 символов)
     */
    totalActivity?: string

    /**
     * Общая масса нетто взрывчатого содержимого в килограммах
     * для каждого вещества или изделия, имеющего отдельный номер ООН.
     * (Обязательно для класса 1)
     * (1-50 символов)
     */
    netExplosiveMass?: string

    /**
     * Общая масса нетто взрывчатого содержимого в килограммах
     * для всех веществ и изделий по сопроводительной ведомости.
     * (Обязательно для класса 1)
     * (1-50 символов)
     */
    totalNetExplosiveMass?: string

    /**
     * Процентный (по объему или массе) состав смеси.
     * Обязательно для класса 2 при перевозке в цистернах.
     * В остальных случаях — "-".
     * (Доп. положения для класса 2)
     * (1-50 символов)
     */
    mixtureComposition?: string

    /**
     * Дата истечения времени удержания (ДД.ММ.ГГГГ).
     * В остальных случаях для класса 2 — "-".
     * (Доп. положения для класса 2)
     */
    retentionExpiryDate?: Date

    /**
     * Контрольная температура, в градусах.
     * Обязательно для классов 4.1 и 5.2, требующих
     * регулирования температуры. В остальных случаях — "-".
     * (1-10 символов)
     */
    controlTemperature?: string

    /**
     * Аварийная температура, в градусах.
     * Обязательно для классов 4.1 и 5.2, требующих
     * регулирования температуры. В остальных случаях — "-".
     * (1-10 символов)
     */
    emergencyTemperature?: string
}

export function formatDangerousGoodsInfo(data: TDangerousGoodsInfo) {
    return {
        "НомООН": data.unNumber,
        "НадОтгНаим": data.shippingName,
        "ТехНаим": data.technicalName,
        "Описание": data.description,
        "Клас": data.hazardClass,
        "КласКод": data.classificationCode ?? "-",
        "ГрУп": data.packingGroup ?? "-",
        "ЗнОп": data.hazardLabel,
        "КодОгрЧерТун": data.tunnelCode ?? "-",
        "НазРадионук": data.radionuclide,
        "ОписФизХимФорм": data.physicalChemicalForm,
        "МаксАкт": data.maxActivity,
        "КатУпак": data.packageCategory,
        "ТрансИндекс": data.transportIndex,
        "ИндексБез": data.criticalitySafetyIndex,
        "ОпозЗнак": data.approvalCertificateId,
        "ПолнАктГр": data.totalActivity,
        "ОбМасНетВзрСод": data.netExplosiveMass,
        "ОбМасНетВзрСодВсех": data.totalNetExplosiveMass,
        "ПроцСмеси": data.mixtureComposition,
        "ДатИстВрУдер": data.retentionExpiryDate && formatDate(data.retentionExpiryDate),
        "КонтТемпер": data.controlTemperature,
        "АварТемпер": data.emergencyTemperature,
    }
}
