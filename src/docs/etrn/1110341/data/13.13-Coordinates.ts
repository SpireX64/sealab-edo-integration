/**
 * Координаты места
 * (КоордТип, таб-13.13)
 */

export type TCoordinates = {
    /**
     * Широта в формате: <ХХ.УУУУУУУУУУУУУ> во всемирной системе
     * геоцентрических координат WGS 84, где:
     * ХХ — градусы в диапазоне от -90 до 90,
     * УУУУУУУУУУУУУ — минуты и секунды, представленные как
     * десятичные доли с точностью до 13 знаков.
     */
    latitude: string

    /**
     * Долгота в формате: <ХXХ.УУУУУУУУУУУУУ> во всемирной системе
     * геоцентрических координат WGS 84, где:
     * ХXХ — градусы в диапазоне от -180 до 180,
     * УУУУУУУУУУУУУ — минуты и секунды, представленные как
     * десятичные доли с точностью до 13 знаков.
     */
    longitude: string
}

export function formatCoordinates({ latitude, longitude }: TCoordinates) {
    return {
        "Широта": latitude,
        "Долгота": longitude,
    }
}
