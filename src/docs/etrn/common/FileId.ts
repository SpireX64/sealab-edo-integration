/**
 * Идентификация файла обмена
 *
 * Общий тип для документов 1110340 (таб-7.3) и 1110341 (таб-13.3).
 * Функции форматирования различаются (разные XML-теги),
 * поэтому определяются на уровне документов.
 */

export type TFileId = {
    /**
     * Идентификатор файла.
     * Содержит (повторяет) имя файла без расширения.
     * (1-255 символов)
     */
    fileId: string

    /**
     * Дата и время формирования файла.
     */
    createdAt: Date

    /**
     * Электронная подпись файла.
     * Представляется в кодировке Base64.
     */
    signBase64: string
}
