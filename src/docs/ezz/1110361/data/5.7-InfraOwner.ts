/**
 * Сведения об организации-владельце объекта инфраструктуры пункта погрузки
 * (ОргВладИнфр, таб-5.7)
 */

export type TInfraOwner = {
    /**
     * Наименование организации-владельца объекта инфраструктуры
     * пункта погрузки.
     * (1-1000 символов)
     */
    name: string

    /**
     * ИНН организации-владельца объекта инфраструктуры
     * пункта погрузки.
     * (10-12 символов)
     */
    inn: string
}

export function formatInfraOwner(data: TInfraOwner) {
    return {
        "НаимВладИнфр": data.name,
        "ИННВладИнфр": data.inn,
    }
}
