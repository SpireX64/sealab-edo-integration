/**
 * Сведения об опасном грузе
 * (СвОпаснГрузТип, таб-5.38)
 */

import { formatDate } from '../../../../helpers'

export type TDangerousGoods = {
    /**
     * Номер ООН.
     * Формат: «UN XXXX», где XXXX — идентификационный номер
     * по списку опасных веществ (ДОПОГ, колонка 1 «№ ООН»).
     * (1-50 символов)
     */
    unNumber: string

    /**
     * Надлежащее отгрузочное наименование.
     * Соответствует номеру ООН (ДОПОГ, колонка 2
     * «Наименование и написание»).
     * (1-2000 символов)
     */
    properShippingName: string

    /**
     * Техническое наименование.
     * (ДОПОГ, колонка 2 «Наименование и написание»,
     * пункт 3.1.2 главы 3.1).
     * (1-2000 символов)
     */
    technicalName?: string

    /**
     * Описание, уточняющее сферу охвата позиции.
     * (ДОПОГ, колонка 2 «Наименование и описание»,
     * пункт 3.1.2 главы 3.1).
     * (1-1000 символов)
     */
    description?: string

    /**
     * Класс опасности грузов.
     * (ДОПОГ, колонка 3a «Класс», глава 2.2 части 2).
     * (1-3 символа)
     */
    hazardClass: string

    /**
     * Классификационный код.
     * (ДОПОГ, колонка 3b «Классификационный код»,
     * глава 2.2 части 2).
     * При отсутствии в справочнике — значение «-».
     * (1-50 символов)
     */
    classificationCode: string

    /**
     * Группа упаковки.
     * (ДОПОГ, колонка 4 «Группа упаковки»,
     * подпункт 2.1.1.3).
     * При отсутствии в справочнике — значение «-».
     * (1-50 символов)
     */
    packingGroup: string

    /**
     * Знак опасности.
     * (ДОПОГ, колонка 5 «Знак опасности»,
     * подпункт 5.2.2).
     * (1-50 символов)
     */
    dangerLabel: string

    /**
     * Код ограничения проезда через туннели.
     * (ДОПОГ, колонка 15 «Трансп. Категория»,
     * глава 8.6 части 8 приложения B).
     * При отсутствии в справочнике — значение «-».
     * (1-50 символов)
     */
    tunnelRestrictionCode: string

    /**
     * Название или символ каждого радионуклида.
     * Дополнительные положения для класса 7.
     * (ДОПОГ, подпункт 5.4.1.2.5.1 (a)).
     * (1-1000 символов)
     */
    radionuclideName?: string

    /**
     * Описание физической и химической формы.
     * Дополнительные положения для класса 7.
     * (ДОПОГ, подпункт 5.4.1.2.5.1 (b)).
     * (1-1000 символов)
     */
    physicalChemicalForm?: string

    /**
     * Максимальная активность радиоактивного содержимого
     * во время перевозки (Бк) или масса делящегося материала (г).
     * Дополнительные положения для класса 7.
     * (ДОПОГ, подпункт 5.4.1.2.5.1 (c)).
     * (1-1000 символов)
     */
    maxActivity?: string

    /**
     * Категория упаковки, транспортного пакета или контейнера.
     * I-БЕЛАЯ, II-ЖЕЛТАЯ, III-ЖЕЛТАЯ.
     * Дополнительные положения для класса 7.
     * (ДОПОГ, подпункт 5.4.1.2.5.1 (d),
     * пункт 5.1.5.3.4).
     * (1-50 символов)
     */
    packagingCategory?: string

    /**
     * Транспортный индекс (TI).
     * Дополнительные положения для класса 7
     * (кроме категории I-БЕЛАЯ).
     * (ДОПОГ, подпункт 5.4.1.2.5.1 (e),
     * пункты 5.1.5.3.1 и 5.1.5.3.2).
     * (1-100 символов)
     */
    transportIndex?: string

    /**
     * Индекс безопасности по критичности для грузов,
     * содержащих делящийся материал.
     * Дополнительные положения для класса 7.
     * (ДОПОГ, подпункт 5.4.1.2.5.1 (f)).
     * (1-100 символов)
     */
    criticalitySafetyIndex?: string

    /**
     * Опознавательный знак для каждого сертификата
     * об утверждении компетентного органа.
     * Дополнительные положения для класса 7.
     * (ДОПОГ, подпункт 5.4.1.2.5.1 (g)).
     * (1-10000 символов)
     */
    approvalCertificateMark?: string

    /**
     * Полная активность груза в виде значения, кратного А2.
     * Для материала с неограниченным А2 — значение «-».
     * Дополнительные положения для класса 7.
     * (ДОПОГ, подпункт 5.4.1.2.5.1 (j)).
     * (1-50 символов)
     */
    totalActivity?: string

    /**
     * Общая масса нетто взрывчатого содержимого
     * в килограммах для каждого вещества или изделия
     * с отдельным номером ООН.
     * Обязательно для класса 1.
     * (1-50 символов)
     */
    netExplosiveMassPerUN?: string

    /**
     * Общая масса нетто взрывчатого содержимого
     * в килограммах для всех веществ и изделий.
     * Обязательно для класса 1.
     * (1-50 символов)
     */
    totalNetExplosiveMass?: string

    /**
     * Процентный (по объему или массе) состав смеси.
     * Дополнительные положения для класса 2
     * (перевозка смесей в цистернах).
     * (ДОПОГ, подпункт 5.4.1.2.2 (a)).
     * (1-50 символов)
     */
    mixturePercentage?: string

    /**
     * Дата истечения времени удержания.
     * Дополнительные положения для класса 2.
     * При отсутствии — значение «-».
     * (ДОПОГ, подпункт 5.4.1.2.2 (d)).
     */
    retentionExpiryDate?: Date

    /**
     * Контрольная температура, в градусах Цельсия.
     * Обязательно для самореактивных веществ и
     * полимеризующихся веществ класса 4.1 и органических
     * пероксидов класса 5.2, требующих регулирования
     * температуры.
     * При отсутствии — значение «-».
     * (ДОПОГ, подпункт 5.4.1.2.3.1).
     * (1-10 символов)
     */
    controlTemperature?: string

    /**
     * Аварийная температура, в градусах Цельсия.
     * Обязательно для самореактивных веществ и
     * полимеризующихся веществ класса 4.1 и органических
     * пероксидов класса 5.2, требующих регулирования
     * температуры.
     * При отсутствии — значение «-».
     * (ДОПОГ, подпункт 5.4.1.2.3.1).
     * (1-10 символов)
     */
    emergencyTemperature?: string
}

export function formatDangerousGoods(data: TDangerousGoods) {
    return {
        "НомООН": data.unNumber,
        "НадОтгНаим": data.properShippingName,
        "ТехНаим": data.technicalName,
        "Описание": data.description,
        "Клас": data.hazardClass,
        "КласКод": data.classificationCode,
        "ГрУп": data.packingGroup,
        "ЗнОп": data.dangerLabel,
        "КодОгрЧерТун": data.tunnelRestrictionCode,
        "НазРадионук": data.radionuclideName,
        "ОписФизХимФорм": data.physicalChemicalForm,
        "МаксАкт": data.maxActivity,
        "КатУпак": data.packagingCategory,
        "ТрансИндекс": data.transportIndex,
        "ИндексБез": data.criticalitySafetyIndex,
        "ОпозЗнак": data.approvalCertificateMark,
        "ПолнАктГр": data.totalActivity,
        "ОбМасНетВзрСод": data.netExplosiveMassPerUN,
        "ОбМасНетВзрСодВсех": data.totalNetExplosiveMass,
        "ПроцСмеси": data.mixturePercentage,
        "ДатИстВрУдер": data.retentionExpiryDate
            ? formatDate(data.retentionExpiryDate)
            : "-",
        "КонтТемпер": data.controlTemperature ?? "-",
        "АварТемпер": data.emergencyTemperature ?? "-",
    }
}
