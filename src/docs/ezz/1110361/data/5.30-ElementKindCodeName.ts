/**
 * Сведения о виде (код) и наименовании адресного элемента
 * (ВидНаимКодТип, таб-5.30)
 */

export type TElementKindCodeName = {
    /**
     * Вид (код) элемента.
     * Для муниципального района/городского округа:
     *   1 — муниципальный район, 2 — городской округ,
     *   3 — внутригородская территория города федерального значения,
     *   4 — муниципальный округ, 5 — федеральная территория.
     * Для городского/сельского поселения:
     *   1 — городское поселение, 2 — сельское поселение,
     *   3 — межселенная территория в составе муниципального района,
     *   4 — внутригородской район городского округа.
     */
    kindCode: string

    /**
     * Наименование элемента.
     * (1-255 символов)
     */
    name: string
}

export function formatElementKindCodeName(data: TElementKindCodeName) {
    return {
        "ВидКод": data.kindCode,
        "Наим": data.name,
    }
}
