/**
 * Общие типы и интерфейсы для саб-клиентов (`src/api/*`).
 */

import type { TOrganization } from "../organization";

/**
 * Транспортный контракт, который `SabyTmsClient` предоставляет саб-клиентам.
 *
 * Инкапсулирует низкоуровневый JSON-RPC запрос и организацию из `login`,
 * не раскрывая внутренний `_rpc` клиента.
 */
export interface ISabyTransport {
    /**
     * Выполняет JSON-RPC запрос к сервисному эндпоинту (`/service/`).
     *
     * @param method - Имя метода (например, `СБИС.ЗаписатьСотрудника`).
     * @param params - Уже собранные параметры (с нужной обёрткой `Параметр`/`Params`/без обёртки).
     */
    request<T = unknown>(method: string, params: object): Promise<T>;

    /**
     * Организация-инициатор, заданная при {@link SabyTmsClient#login}.
     * Используется саб-клиентами для автоматической подстановки `НашаОрганизация`.
     */
    readonly organization: TOrganization | undefined;
}

// ─── Пагинация ───────────────────────────────────────────────────────────────

/**
 * Пагинация списков, использующих «Страницу» (например, `СБИС.СписокСотрудников`).
 * @see TListPosition — для списков с «Позицией» (доверие).
 */
export type TListPagination = {
    /** Размер страницы (1..500). */
    pageSize?: number;

    /** Номер страницы (0..2 000 000). */
    page?: number;
};

/**
 * Пагинация списков, использующих «Позицию» (например, `СБИС.СписокДоверий`).
 */
export type TListPosition = {
    /** Размер страницы (1..500). */
    pageSize?: number;

    /** Позиция, начиная с которой получаем данные. */
    position?: number;
};

/** Навигация в ответе спискового метода. */
export type TListNavigation = {
    /** Есть ли ещё записи. */
    "ЕстьЕще"?: string;

    /** Размер страницы. */
    "РазмерСтраницы"?: string;

    /** Номер страницы (для списков с пагинацией по страницам). */
    "Страница"?: string;
};

/** Общий контейнер ответа спискового метода. */
export type TListResult<T> = {
    /** Навигация по результату. */
    "Навигация"?: TListNavigation;

    /** Результат — массив сущностей (ключ зависит от метода). */
    [key: string]: T[] | TListNavigation | undefined;
};
