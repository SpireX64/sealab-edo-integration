/**
 * Типы, используемые клиентом Saby TMS при работе с документами.
 */

import type { DocumentType } from "./docs/shared";
import type { TSabyAction } from "./saby";
import type { TOrganization } from "./organization";

export type { TDocumentAttachment } from "./docs/shared";
export type { TOrganization };

// ─── Вложения ────────────────────────────────────────────────────────────────

/** Файл сгенерированного вложения (XML в base64). */
export type TAttachmentFile = {
    "Файл": {
        /** Содержимое файла (XML) в кодировке Base64. */
        "ДвоичныеДанные": string;
        /** Имя файла (например, ON_TRNACLGROT____0_20260311_.xml). */
        "Имя": string;
    };
};

/**
 * Результат СБИС.СгенерироватьВложение — массив вложений,
 * каждое из которых содержит файл.
 *
 * Поля `Тип` и `Подтип` — эхо из запроса (`Документ.Вложение`),
 * добавляются клиентом. Они позволяют `writeDocument` автоматически выводить
 * `Документ.Тип` / `Документ.Регламент.Название`.
 */
export type TGeneratedAttachment = {
    "Вложение": TAttachmentFile[];

    /** Эхо `Вложение.Тип` — тип документа (ЭТрН / ЗаказЗаявка / ЭПЛ). */
    "Тип": DocumentType;

    /** Эхо `Вложение.Подтип` — номер формата (1110339, 1110380, ...). */
    "Подтип": string;
};

// ─── Карточка документа (ответ ЗаписатьДокумент / ПрочитатьДокумент) ───────

/** Вложение в карточке документа (ответ API). */
export type TDocumentCardAttachment = {
    "Идентификатор": string;
    "Подтип"?: string;
    "Тип"?: string;
    "Название"?: string;
    "Направление"?: string;
    "Файл"?: {
        "Имя"?: string;
        "Хеш"?: string;
    };
};

/** Состояние документа (ответ API). */
export type TDocumentState = {
    "Код"?: string;
    "Название"?: string;
    "Описание"?: string;
};

/**
 * Карточка документа — результат СБИС.ЗаписатьДокумент и СБИС.ПрочитатьДокумент.
 * Типизированы только поля, на которые опираются клиент и e2e-тесты.
 */
export type TDocumentCard = {
    "Идентификатор": string;
    "Название"?: string;
    "Номер"?: string;
    "Дата"?: string;
    "Тип"?: string;
    "Подтип"?: string;
    "Направление"?: string;
    "Состояние"?: TDocumentState;
    "Вложение"?: TDocumentCardAttachment[];
};

// ─── Параметры методов ───────────────────────────────────────────────────────

/** Учётные данные для {@link SabyTmsClient#login}. */
export type TLoginCredentials = {
    /** Логин от личного кабинета Saby. */
    login: string;

    /** Пароль от личного кабинета Saby. */
    password: string;

    /**
     * Организация, от имени которой выполняется документооборот.
     * Создаётся фабрикой {@link organization}.
     */
    organization: TOrganization;
};

/** Опции создания нового документа (Т1) — СБИС.ЗаписатьДокумент. */
export type TWriteDocumentOptions = {
    /** Дополнительные поля документа (например, Медосмотр/Техосмотр для ЭПЛ). */
    extra?: Record<string, unknown>;
};

/** Опции подготовки действия (подписи) — СБИС.ПодготовитьДействие. */
export type TPrepareActionOptions = {
    /**
     * Название действия (Этап.Действие.Название).
     * @see EtRnAction — действия ЭТрН
     * @see EzzAction — действия ЭЗЗ
     * @see EplAction — действия ЭПЛ
     */
    action: TSabyAction;

    /**
     * Отпечаток сертификата КЭП подписанта
     * (Этап.Действие.Сертификат.Отпечаток) — SHA-1 (40 hex-символов),
     * которым подписывается документ.
     */
    certificateThumbprint: string;

    /** Комментарий (Этап.Действие.Комментарий). Необязателен. */
    comment?: string;

    /** Название этапа документооборота (Этап.Название), если требуется. */
    stageName?: string;
};

/** Опции выполнения действия — СБИС.ВыполнитьДействие. */
export type TExecuteActionOptions = {
    /** Этап документооборота с подписанными данными. */
    stage: unknown;

    /** Тип ключа подписи (Ключ.Тип), обычно "Клиентский". */
    keyType?: string;
};

/** Опции списка изменений — СБИС.СписокИзменений. */
export type TListChangesOptions = {
    /** Тип документа (семейство) для поиска без карточки. */
    documentType?: DocumentType;

    /** Направление документооборота. */
    direction?: "Входящий" | "Исходящий";

    /** Нижняя граница даты/времени изменений (ДатаВремяС). */
    since?: string;

    /** Дополнительные поля (ДопПоля), например "Расширение,ЭПД". */
    extraFields?: string;

    /** Размер страницы (Навигация.РазмерСтраницы). */
    pageSize?: string;
};
