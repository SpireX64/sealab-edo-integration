/**
 * Типы, используемые клиентом Saby TMS при работе с документами.
 */

export type { TDocumentAttachment } from "./docs/shared";

/**
 * Параметры создания нового документа (Т1) — СБИС.ЗаписатьДокумент.
 */
export type TWriteDocumentParams = {
    /** Реквизиты организации-инициатора (НашаОрганизация). */
    organization: unknown;

    /**
     * Сгенерированное вложение (XML в base64) — результат
     * `SabyTmsClient#generateAttachment`.
     */
    attachment: unknown;

    /**
     * Название регламента (Регламент.Название), например:
     * "Транспортная накладная", "Заказ на перевозку", "ЭПЛ".
     */
    regulationName: string;

    /**
     * Тип документа (Тип), например:
     * "ConsignmentNote", "TransportOrder", "Waybill".
     */
    documentType: string;
};

/**
 * Параметры добавления титула (Т2+) к существующему документу — СБИС.ЗаписатьВложение.
 */
export type TWriteAttachmentParams = {
    /** Идентификатор входящего документа (Идентификатор). */
    identifier: string;

    /** Сгенерированное вложение (XML в base64). */
    attachment: unknown;
};

/**
 * Параметры подготовки подписи — СБИС.ПодготовитьДействие.
 */
export type TPrepareActionParams = {
    /** Идентификатор документа. */
    identifier: string;

    /**
     * Действие (Действие), например: "Отправить", "Погружен",
     * "Принят", "Выпущен", "Отклонить".
     */
    action: string;

    /** Этап документооборота (Этап), если требуется. */
    stage?: string;

    /** Отпечаток сертификата КЭП (ОтпечатокПодписи). */
    certificateThumbprint?: string;

    /** Комментарий (например, причина отклонения). */
    comment?: string;
};

/**
 * Параметры выполнения действия — СБИС.ВыполнитьДействие.
 */
export type TExecuteActionParams = {
    /** Идентификатор документа. */
    identifier: string;

    /** Действие (Действие). */
    action: string;

    /** Этап документооборота (Этап) с подписанными данными. */
    stage?: unknown;

    /** Тип ключа подписи (Ключ.Тип), обычно "Клиентский". */
    keyType?: string;
};

/**
 * Параметры получения списка изменений/статусов — СБИС.СписокИзменений.
 * Фильтры задаются произвольными ключами (например, Направление, ДатаВремяС).
 */
export type TListChangesParams = Record<string, unknown>;
