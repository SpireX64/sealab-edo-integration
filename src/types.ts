/**
 * Типы, используемые клиентом Saby TMS при работе с документами.
 */

export type { TDocumentAttachment } from "./docs/shared";

// ─── Организация (НашаОрганизация) ───────────────────────────────────────────

/** Организация — юридическое лицо (СвЮЛ). */
export type TLegalOrganization = {
    "СвЮЛ": {
        "ИНН": string;
        "КПП"?: string;
    };
};

/** Организация — физическое лицо (СвФЛ). */
export type TIndividualOrganization = {
    "СвФЛ": {
        "ИНН": string;
    };
};

/** Организация — индивидуальный предприниматель (СвИП). */
export type TEntrepreneurOrganization = {
    "СвИП": {
        "ИНН": string;
        "ОГРНИП"?: string;
    };
};

/**
 * Реквизиты организации-инициатора, передаваемые в `НашаОрганизация`.
 * Передаётся только идентифицирующая часть (СвЮЛ / СвФЛ / СвИП).
 */
export type TOrganization =
    | TLegalOrganization
    | TIndividualOrganization
    | TEntrepreneurOrganization;

// ─── Вложения ────────────────────────────────────────────────────────────────

/** Файл сгенерированного вложения (XML в base64). */
export type TAttachmentFile = {
    "Файл": {
        /** Содержимое файла (XML) в кодировке Base64. */
        "ДвоичныеДанные": string;
        /** Имя файла (например, ON_TRNACLGROT____0_20260311_.xml). */
        "Имя": string;
    };
};

/**
 * Результат СБИС.СгенерироватьВложение — массив вложений,
 * каждое из которых содержит файл.
 */
export type TGeneratedAttachment = {
    "Вложение": TAttachmentFile[];
};

// ─── Карточка документа (ответ ЗаписатьДокумент / ПрочитатьДокумент) ───────

/** Вложение в карточке документа (ответ API). */
export type TDocumentCardAttachment = {
    "Идентификатор": string;
    "Подтип"?: string;
    "Тип"?: string;
    "Название"?: string;
    "Направление"?: string;
    "Файл"?: {
        "Имя"?: string;
        "Хеш"?: string;
    };
};

/** Состояние документа (ответ API). */
export type TDocumentState = {
    "Код"?: string;
    "Название"?: string;
    "Описание"?: string;
};

/**
 * Карточка документа — результат СБИС.ЗаписатьДокумент и СБИС.ПрочитатьДокумент.
 * Типизированы только поля, на которые опираются клиент и e2e-тесты.
 */
export type TDocumentCard = {
    "Идентификатор": string;
    "Название"?: string;
    "Номер"?: string;
    "Дата"?: string;
    "Тип"?: string;
    "Подтип"?: string;
    "Направление"?: string;
    "Состояние"?: TDocumentState;
    "Вложение"?: TDocumentCardAttachment[];
};

// ─── Параметры методов ───────────────────────────────────────────────────────

/** Параметры создания нового документа (Т1) — СБИС.ЗаписатьДокумент. */
export type TWriteDocumentParams = {
    /** Реквизиты организации-инициатора (НашаОрганизация). */
    organization: TOrganization;

    /** Сгенерированное вложение — результат generateAttachment. */
    attachment: TGeneratedAttachment;

    /** Название регламента (Регламент.Название). */
    regulationName: string;

    /** Тип документа (Тип): "ConsignmentNote" | "TransportOrder" | "Waybill". */
    documentType: string;

    /** Дополнительные поля документа (например, Медосмотр/Техосмотр для ЭПЛ). */
    extra?: Record<string, unknown>;
};

/** Параметры добавления титула (Т2+) — СБИС.ЗаписатьВложение. */
export type TWriteAttachmentParams = {
    /** Идентификатор входящего документа (Идентификатор). */
    identifier: string;

    /** Сгенерированное вложение — результат generateAttachment. */
    attachment: TGeneratedAttachment;
};

/** Параметры подготовки действия (подписи) — СБИС.ПодготовитьДействие. */
export type TPrepareActionParams = {
    /** Идентификатор документа. */
    identifier: string;

    /** Название действия (Этап.Действие.Название): "Отправить", "Принят", ... */
    action: string;

    /** Комментарий (Этап.Действие.Комментарий). */
    comment?: string;

    /** Отпечаток сертификата КЭП (Этап.Действие.Сертификат.Отпечаток). */
    certificateThumbprint?: string;

    /** Название этапа документооборота (Этап.Название), если требуется. */
    stageName?: string;
};

/** Параметры выполнения действия — СБИС.ВыполнитьДействие. */
export type TExecuteActionParams = {
    /** Идентификатор документа. */
    identifier: string;

    /** Название действия (Этап.Действие.Название). */
    action: string;

    /** Этап документооборота с подписанными данными. */
    stage?: unknown;

    /** Тип ключа подписи (Ключ.Тип), обычно "Клиентский". */
    keyType?: string;
};

/** Фильтр списка изменений — СБИС.СписокИзменений. */
export type TListChangesFilter = {
    /** Тип документа: "Waybill" | "ConsignmentNote" | "TransportOrder". */
    "Тип"?: string;

    /** Нижняя граница даты/времени изменений (ДатаВремяС). */
    "ДатаВремяС"?: string;

    /** Идентификатор конкретного документа. */
    "ИдентификаторДокумента"?: string;

    /** Дополнительные поля (ДопПоля), например "Расширение,ЭПД". */
    "ДопПоля"?: string;

    /** Навигация по страницам. */
    "Навигация"?: {
        "РазмерСтраницы"?: string;
    };
};
