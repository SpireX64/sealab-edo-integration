"""Компилирует ограничения трёх XSD поручения в автономные TS-данные.

Запуск из любого каталога: python3 scripts/generate-exp-schema.py [--check].
Неподдерживаемая конструкция XSD останавливает генерацию.
"""
import hashlib
import json
from pathlib import Path
import sys
import xml.etree.ElementTree as ET

PACKAGE = Path(__file__).resolve().parents[1]
XSD = PACKAGE / "schemas/exp"
NS = "{http://www.w3.org/2001/XMLSchema}"
FACETS = {"length", "minLength", "maxLength", "totalDigits", "fractionDigits", "pattern", "enumeration", "minInclusive", "maxInclusive"}
IGNORED = {"annotation"}


def children(node):
    return [child for child in node if child.tag.removeprefix(NS) not in IGNORED]


def compile_schema(path):
    root = ET.parse(path).getroot()
    definitions = {e.get("name"): e for e in root if e.tag in (NS + "simpleType", NS + "complexType")}
    pool = []
    indices = {}

    def intern(value):
        key = json.dumps(value, ensure_ascii=False, sort_keys=True)
        if key not in indices:
            indices[key] = len(pool)
            pool.append(value)
        return indices[key]

    def datatype(node):
        ref = node.get("type")
        if ref:
            if ref.startswith("xs:"):
                assert ref in ("xs:string", "xs:integer", "xs:decimal"), ref
                return intern({"kind": "simple", "base": ref[3:], "facets": {}})
            return datatype(definitions[ref])
        tag = node.tag.removeprefix(NS)
        if tag in ("element", "attribute"):
            types = children(node)
            assert len(types) == 1
            return datatype(types[0])
        if tag == "simpleType":
            restriction, = children(node)
            assert restriction.tag == NS + "restriction"
            base = restriction.get("base")
            facets = {}
            if not base.startswith("xs:"):
                inherited = pool[datatype(definitions[base])]
                base = "xs:" + inherited["base"]
                facets = dict(inherited["facets"])
            for facet in children(restriction):
                name = facet.tag.removeprefix(NS)
                assert name in FACETS, name
                value = facet.get("value")
                if name in ("pattern", "enumeration"):
                    facets.setdefault(name, []).append(value)
                else:
                    facets[name] = int(value)
            assert base in ("xs:string", "xs:integer", "xs:decimal"), base
            return intern({"kind": "simple", "base": base[3:], "facets": facets})
        assert tag == "complexType", tag
        attributes, model = {}, []
        for child in children(node):
            kind = child.tag.removeprefix(NS)
            if kind == "attribute":
                attributes[child.get("name")] = {"type": datatype(child), "required": child.get("use") == "required"}
            else:
                assert kind in ("sequence", "choice"), kind
                model.append(particle(child))
        return intern({"kind": "complex", "attributes": attributes, "model": model})

    def particle(node):
        kind = node.tag.removeprefix(NS)
        if kind == "element":
            maximum = node.get("maxOccurs", "1")
            return {"kind": kind, "name": node.get("name"), "min": int(node.get("minOccurs", "1")), "max": None if maximum == "unbounded" else int(maximum), "type": datatype(node)}
        assert kind in ("sequence", "choice") and not node.attrib, (kind, node.attrib)
        return {"kind": kind, "children": [particle(c) for c in children(node)]}

    element, = root.findall(NS + "element")
    root_type = datatype(element)
    return {"file": path.name, "sha256": hashlib.sha256(path.read_bytes()).hexdigest(), "root": root_type, "types": pool}


schemas = {knd: compile_schema(next(XSD.glob(prefix + "_*.xsd"))) for knd, prefix in [("1110486", "ON_POREXPKLT"), ("1110487", "ON_POREXPEXP"), ("1110488", "ON_POREXPOTZ")]}
output = '// Generated by scripts/generate-exp-schema.py. Do not edit.\nimport type { Schema } from "./schema-types";\n\n'
for knd, schema in schemas.items():
    # Одно определение типа на строку, без тысяч строк форматирующего шума.
    output += 'export const schema' + knd + ': Schema = {\n'
    for key in ("file", "sha256", "root"):
        output += '    ' + key + ': ' + json.dumps(schema[key], ensure_ascii=False) + ',\n'
    output += '    types: [\n'
    for datatype in schema["types"]:
        output += '        // prettier-ignore\n        ' + json.dumps(datatype, ensure_ascii=False, separators=(",", ":")) + ',\n'
    output += '    ],\n};\n' 
target = PACKAGE / "src/docs/exp/validation/schemas.generated.ts"
if "--check" in sys.argv:
    assert target.read_text() == output, "Перегенерируйте schemas.generated.ts"
else:
    target.write_text(output)
